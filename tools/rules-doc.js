'use strict';
// יוצר את docs/rules.md: רשימה מלאה של כל החוקים בפרויקט, כדי שכל אחד יוכל לקרוא ממה הסימולטור בנוי
// ולדבר על זה עם כל בינה מלאכותית (Gemini, ChatGPT, Claude). רץ אוטומטית מתוך tools/build.js.
// לא עורכים את docs/rules.md ידנית: משנים את js/rulebook.js, את js/rules.js או את הטקסט כאן, ובונים מחדש.
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const read = f => fs.readFileSync(path.join(root, f), 'utf8');

const ctx = vm.createContext({ Math, JSON, Object, Array, Set, Map });
for (const f of ['js/theory-data.js', 'js/rulebook.js']) vm.runInContext(read(f).replace(/^'use strict';/, '').replace(/^const (\w+) =/gm, 'var $1 ='), ctx);
const { RULEBOOK, RULE_CATS, THEORY } = ctx;
const qByN = new Map(THEORY.map(q => [q.n, q]));

// כל העבירות שהבוחן בודק: this.report('מפתח', 'הודעה', חמורה, ...)
const src = read('js/rules.js');
const checks = new Map();
const re = /this\.report\('(\w+)',\s*((?:(?!this\.report\()[\s\S])*?),\s*([\w.!]+)\s*,\s*time/g;
let m;
while ((m = re.exec(src))) {
  const [, key, msgExpr, sev] = m;
  const msgs = [...msgExpr.matchAll(/(['`])((?:(?!\1).)*)\1/g)].map(x => x[2].replace(/\$\{[^}]*\}/g, '…')).filter(t => /[א-ת]/.test(t));
  const c = checks.get(key) || { msgs: new Set(), severe: false };
  msgs.forEach(t => c.msgs.add(t));
  if (sev === 'true') c.severe = true;
  checks.set(key, c);
}

const L = [];
const P = (...a) => L.push(...a);
P('# כל החוקים של "מגרש תרגול נהיגה"', '',
  '> הקובץ הזה נוצר אוטומטית מתוך הקוד (`node tools/build.js`). אל תערכו אותו ידנית.',
  '', '## איך משתמשים בקובץ הזה', '',
  '- **לקרוא ולהבין** ממה הסימולטור בנוי: אילו חוקי תנועה הוא מלמד, מה הבוחן בודק, וכמה נקודות יורדות על כל עבירה.',
  '- **לדבר עם כל בינה מלאכותית** (Gemini, ChatGPT, Claude ועוד): מעתיקים את כל הקובץ לצ\'אט ושואלים, למשל: "האם יש כאן חוק שגוי לפי חוק התנועה בישראל?" או "אילו חוקים חסרים לקראת הטסט?"',
  '- **לבקש תיקון או תוספת:** כותבים לסוכן שעורך את הפרויקט (Gemini CLI, Jules, Claude), למשל: "תוסיף חוק על ... לפי שאלה מספר ... במאגר". ההנחיות לסוכנים נמצאות ב-`AGENTS.md`.',
  '- **מספרי השאלות** בכל חוק הם המקור שלו במאגר שאלות התיאוריה הרשמי של משרד התחבורה (נמצא בפרויקט ב-`js/theory-data.js`). חוק בלי מקור מסומן "לבדיקה".',
  '');

P('## איך הסימולטור עובד', '',
  '### שליטה ברכב',
  '- **חץ למעלה:** גז (תמיד קדימה). **חץ למטה:** בלם. בהילוך אחורי (R): חץ למטה נוסע אחורה, וחץ למעלה מחזיר להילוך D.',
  '- **חצים ימינה ושמאלה:** סיבוב ההגה. בלי לחיצה, הרכב נשאר לבד במרכז הנתיב שהוא נמצא בו ומתעקל עם הכביש, גם בתוך כיכר (בנתיב הפנימי או החיצוני). את הפנייה בצומת, את החלפת הנתיב ואת היציאה מהכיכר הנהג עושה בעצמו עם החצים.',
  '- **Z / C:** איתות שמאלה / ימינה. **X:** ביטול איתות. **רווח:** צופר. **M:** הילוך אחורי. **V:** החלפת מצלמה.',
  '- **B / N:** חניה בצד שמאל / ימין (רק בנהיגה מסייעת).',
  '- **נהיגה מסייעת** (בהגדרות): החצים רק בוחרים נתיב או פנייה, והרכב מבצע לבד.',
  '',
  '### העולם',
  '- נוסעים בצד ימין (ישראל). רוחב נתיב 3.5 מ\'. מדרכות עם אבני שפה: אדום-לבן = אסור לחנות, כחול-לבן = מותר לחנות.',
  '- **צמתים:** פינות המדרכה מעוגלות (רדיוס 6 מ\') כדי שאפשר לפנות בלי לעלות על המדרכה. ברמזור יש פנס מעל הנתיבים, פנס בצד, ועוד פנס בצד הרחוק של הצומת, כך שרואים אותו גם כשעומדים צמוד לקו העצירה.',
  '- **כיכרות:** נוסעים נגד כיוון השעון. בכיכר דו-נתיבית יש נתיב פנימי וחיצוני.',
  '- **תנועה:** רכבים, אוטובוסים, רוכבי אופניים, הולכי רגל במעברי חציה, ומדי פעם רכב ביטחון עם סירנה. "מנהל תנועה" שולח רכבים מהכיוונים האחרים לצומת או לכיכר שהנהג מתקרב אליהם, כך שיגיעו בערך יחד איתו, כדי שיהיה צריך לתת זכות קדימה כמעט בכל צומת.',
  '- **מזג אוויר:** יום, גשם (צריך לנסוע לאט יותר ולשמור מרחק גדול יותר) ולילה (צריך אורות).',
  '',
  '### הבוחן והציון',
  '- מתחילים מ-100 נקודות. **עבירה רגילה:** מורידה 5 נקודות. **עבירה חמורה:** מורידה 15 נקודות ונחשבת כישלון בטסט.',
  '- הבוחן נותן הוראות בקול ("ברמזור הבא פנה ימינה", "חנה בצד ימין" וכו\') ובודק שביצעת אותן.',
  '- כל עבירה מקושרת לחוק בספר החוקים, כך שאפשר לקרוא למה זו עבירה.',
  '');

P('## ספר החוקים', '', `סה"כ ${RULEBOOK.length} חוקים, ${RULEBOOK.filter(r => r.src.length).length} מהם מאומתים מול המאגר הרשמי.`, '');
for (const cat of RULE_CATS) {
  const rules = RULEBOOK.filter(r => r.cat === cat);
  if (!rules.length) continue;
  P(`### ${cat}`, '');
  for (const r of rules) {
    P(`#### ${r.title}${r.src.length ? '' : ' (לבדיקה: אין מקור במאגר)'}`, '', r.text, '');
    if (r.keys && r.keys.length) P(`- **הבוחן בודק:** ${r.keys.map(k => '`' + k + '`').join(', ')}`);
    for (const n of r.src) {
      const q = qByN.get(n);
      if (q) P(`- **שאלה ${n} במאגר:** ${q.q} **תשובה:** ${q.a[q.c]}`);
    }
    P(`- מזהה: \`${r.id}\``, '');
  }
}

P('## כל העבירות שהבוחן בודק', '',
  `סה"כ ${checks.size} סוגי עבירות. הקוד נמצא ב-\`js/rules.js\`, והמפתח מקשר לחוק בספר החוקים (\`keys\` ב-\`js/rulebook.js\`).`, '',
  '| מפתח | חומרה | מה הבוחן אומר | החוק בספר |', '|---|---|---|---|');
for (const [key, c] of [...checks].sort((a, b) => a[0].localeCompare(b[0]))) {
  const rule = RULEBOOK.find(r => (r.keys || []).includes(key));
  P(`| \`${key}\` | ${c.severe ? 'חמורה (15)' : 'רגילה (5)'} | ${[...c.msgs].join(' / ').replace(/\|/g, '\\|')} | ${rule ? rule.title : '—'} |`);
}
P('');

fs.mkdirSync(path.join(root, 'docs'), { recursive: true });
fs.writeFileSync(path.join(root, 'docs/rules.md'), L.join('\n'));
console.log('built docs/rules.md:', RULEBOOK.length, 'rules,', checks.size, 'examiner checks');
